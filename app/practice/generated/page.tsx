"use client";
import { useCallback, useEffect, useMemo, useState } from "react";
import { useRouter, useSearchParams } from "next/navigation";
import PracticeProblems from "@/app/components/PracticeProblems";
import SiteNav from "@/app/components/SiteNav";
import PageLoader from "@/app/components/PageLoader";
import { useAuth } from "@/app/components/AuthProvider";
import type { PracticeProblem } from "@/lib/practice/types";

export default function GeneratedPracticePage() {
  const router = useRouter();
  const params = useSearchParams();
  const { user, getIdToken, loading: authLoading } = useAuth();

  const courseSlug = params.get("courseSlug") ?? "general";
  const courseTitle = params.get("courseTitle") ?? "AP course";
  const unitNumber = Number(params.get("unitNumber")) || 1;
  const count = Math.max(1, Math.min(8, Number(params.get("count")) || 4));
  const similarTo = params.get("similarTo") ?? "";

  // A unique session id keeps generated-practice progress + whiteboard
  // state isolated from real unit practice.
  const sessionId = useMemo(() => {
    if (typeof window === "undefined") return "session";
    const existing = window.sessionStorage.getItem("fp-gen-session");
    if (existing) return existing;
    const next = `s${Date.now().toString(36)}`;
    window.sessionStorage.setItem("fp-gen-session", next);
    return next;
  }, []);

  const [problems, setProblems] = useState<PracticeProblem[] | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  const load = useCallback(async () => {
    setLoading(true);
    setError("");
    try {
      const token = await getIdToken();
      const res = await fetch("/api/generate-practice", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          ...(token ? { Authorization: `Bearer ${token}` } : {}),
        },
        body: JSON.stringify({
          courseSlug,
          courseTitle,
          unitNumber,
          count,
          similarTo,
        }),
      });
      const data = await res.json();
      if (!res.ok) {
        setError(data?.message || data?.error || "Generation failed.");
      } else if (Array.isArray(data.problems) && data.problems.length > 0) {
        setProblems(data.problems);
      } else {
        setError("No problems returned.");
      }
    } catch (e: any) {
      setError(e?.message || "Generation failed.");
    } finally {
      setLoading(false);
    }
  }, [courseSlug, courseTitle, unitNumber, count, similarTo, getIdToken]);

  useEffect(() => {
    if (authLoading) return;
    if (!user) {
      router.push(
        `/signin?next=${encodeURIComponent(
          "/practice/generated?" + params.toString()
        )}`
      );
      return;
    }
    if (problems === null && !loading) load();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [authLoading, user]);

  function regenerate() {
    if (typeof window !== "undefined") {
      const next = `s${Date.now().toString(36)}`;
      window.sessionStorage.setItem("fp-gen-session", next);
    }
    setProblems(null);
    load();
  }

  if (authLoading) return <PageLoader />;

  return (
    <main className="bg-paper text-body">
      <SiteNav maxWidth="max-w-6xl" />
      <div className="mx-auto max-w-3xl px-6 py-10">
        <button
          onClick={() => router.back()}
          className="inline-flex items-center gap-1 text-[13px] text-muted hover:text-ink"
        >
          <span aria-hidden="true">←</span>
          <span>Back</span>
        </button>
        <div className="mt-3 flex flex-wrap items-baseline justify-between gap-3">
          <div>
            <div className="text-[11px] font-medium uppercase tracking-[0.14em] text-muted">
              Generated practice
            </div>
            <h1 className="mt-1 font-serif text-[32px] leading-tight text-ink">
              {courseTitle} · Unit {unitNumber}
            </h1>
          </div>
          <button
            onClick={regenerate}
            disabled={loading}
            className="rounded-md border border-orange/40 bg-orange-tint px-3 py-1.5 text-xs font-medium text-orange-ink hover:border-orange disabled:opacity-50"
          >
            {loading ? "Generating…" : "Regenerate"}
          </button>
        </div>
        <p className="mt-2 max-w-2xl text-[14px] text-muted">
          {similarTo
            ? "Fresh problems styled after the one you came from."
            : `Freshly generated by the AI tutor. Whiteboard, hints, and AI grading all work just like the unit practice.`}
        </p>

        <div className="mt-8">
          {loading && !problems && (
            <div className="rounded-md border border-hair bg-offwhite p-6 text-sm text-muted">
              Generating {count} practice problem{count === 1 ? "" : "s"}…
              this usually takes 5–10 seconds.
            </div>
          )}
          {error && (
            <div className="rounded-md border border-red-300 bg-red-50 p-4 text-[13px] text-red-800">
              {error}
            </div>
          )}
          {problems && (
            <PracticeProblems
              problems={problems}
              courseSlug={`generated:${courseSlug}:${sessionId}`}
              unitNumber={unitNumber}
              courseTitle={courseTitle}
            />
          )}
        </div>
      </div>
    </main>
  );
}
